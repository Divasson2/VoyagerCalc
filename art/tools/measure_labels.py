"""Measure the gold (f) and blue (g) legends of every key on the photo faces.

For each key cap (art/faces/geometry.json) it finds:
  * the blue legend on the cap's lower front: the topmost row of blue pixels inside the cap;
  * the gold legend above the cap: the rows of gold pixels between the row above and the cap.
The per-face numbers (blue band = bottom part of a cap, as a fraction of the normal cap height;
gold band = the strip above the cap) are written to app/Sources/Models/PhotoFaceLabels.swift
and a report to art/faces/labels.json. Run after make_faces.py.
"""
import json, os, statistics as st
from PIL import Image
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
G = json.load(open(os.path.join(ROOT, 'art/faces/geometry.json')))

def masks(a):
    r, g, b = a[..., 0].astype(int), a[..., 1].astype(int), a[..., 2].astype(int)
    blue = (b > 150) & (r < 160) & (b > r + 60) & (b > g + 5)
    gold = (r > 170) & (g > 110) & (b < 110) & (r > b + 90)
    return blue, gold

out, report = {}, {}
for m, d in G.items():
    im = np.asarray(Image.open(os.path.join(ROOT, f'art/faces/face_{m}.png')).convert('RGB'))
    H, W = im.shape[:2]
    blue, gold = masks(im)
    keys = {int(k): v for k, v in (d['keys'] if isinstance(d['keys'], dict) else json.loads(d['keys'].replace("'", '"'))).items()}
    capH = keys[24][3]
    tops, golds, per = [], [], {}
    for c, (x, y, w, h) in keys.items():
        x0, x1 = int(x * W), int((x + w) * W)
        y0, y1 = int(y * H), int((y + h) * H)
        # the legend is the lowest run of blue rows (glints of blue near the cap's top edge are not)
        rows = np.where(blue[y0:y1, x0:x1].sum(axis=1) >= 3)[0]
        if len(rows):
            run = [rows[-1]]
            for rr in rows[::-1][1:]:
                if run[-1] - rr <= 3: run.append(rr)
                else: break
            rows = np.array(run)
        bt = (y1 - (y0 + rows.min())) / H if len(rows) else None       # blue band height from the cap bottom
        above = keys.get(c - 10)
        ya = int((above[1] + above[3]) * H) if above else max(0, y0 - int(capH * H * 0.9))
        grows = np.where(gold[ya:y0, x0:x1].sum(axis=1) >= 3)[0]
        gt = (y0 - (ya + grows.min())) / H if len(grows) else None      # gold legend reach above the cap
        per[c] = {'blue_from_bottom': bt and round(bt, 5), 'gold_above': gt and round(gt, 5)}
        if bt and c not in (25, 30, 31, 32): tops.append(bt / capH)
        if gt: golds.append(gt)
    frac = round(max(tops) + 0.04, 3)            # blue zone: bottom part of the cap, a little margin
    out[m] = {'gZoneFraction': frac, 'capH': capH, 'blueTopsMedian': round(st.median(tops), 3), 'goldMax': round(max(golds), 5)}
    report[m] = {'summary': out[m], 'keys': per}
    print(m, out[m])
json.dump(report, open(os.path.join(ROOT, 'art/faces/labels.json'), 'w'), indent=1)
names = {'12c': 'hp12c', '15c': 'hp15c', '16c': 'hp16c'}
with open(os.path.join(ROOT, 'app/Sources/Models/PhotoFaceLabels.swift'), 'w') as f:
    f.write('''// SPDX-License-Identifier: MIT
// Copyright (c) 2026 José González Divassón
//
// PhotoFaceLabels.swift - GENERATED by art/tools/measure_labels.py; do not edit by hand.
// Where the blue (g) legend sits on each photo face: the bottom part of a key cap, as a
// fraction of the normal cap height (the topmost blue pixel of any legend, plus a margin).
// The gold (f) legend is the strip above the cap inside the key's hit area.

import Foundation

extension PhotoFace {
    static let gZoneFractions: [String: CGFloat] = [
''')
    for m in ('12c', '15c', '16c'):
        f.write(f'        "face_{m}": {out[m]["gZoneFraction"]},\n')
    f.write('    ]\n}\n')
