"""Write app/Sources/Core/PDFFontMetrics.swift: glyph widths (1/1000 em) of the standard PDF fonts
Helvetica, Helvetica-Bold, Courier and Symbol, by byte of their encodings (WinAnsi / Symbol),
taken from the Adobe core-font metrics shipped with reportlab. Run once; the output is checked in."""
import os
from reportlab.pdfbase import pdfmetrics
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def row(name): return pdfmetrics.getFont(name).widths
out = ['// SPDX-License-Identifier: MIT', '//', '// PDFFontMetrics.swift - GENERATED by app/tools/gen_pdf_metrics.py; do not edit by hand.',
       '// Widths (1/1000 em) of the PDF standard fonts by encoded byte: Helvetica, Helvetica-Bold and',
       '// Courier in WinAnsiEncoding, Symbol in its built-in encoding (Adobe core font metrics).', '',
       'enum PDFFontMetrics {']
for var, name in (('helvetica', 'Helvetica'), ('helveticaBold', 'Helvetica-Bold'), ('courier', 'Courier'), ('symbol', 'Symbol')):
    w = row(name)
    out.append(f'    static let {var}: [UInt16] = [')
    for i in range(0, 256, 16): out.append('        ' + ', '.join(str(int(x)) for x in w[i:i + 16]) + ',')
    out.append('    ]')
out.append('}')
open(os.path.join(ROOT, 'Sources', 'Core', 'PDFFontMetrics.swift'), 'w').write('\n'.join(out) + '\n')
print('ok')
